class GErr(Exception):
    pass


class FGcmd:
    def __init__(self, **p):
        self.p = {k.upper(): str(v) for k, v in p.items()}
        self.out = []

    def get(self, k, default=None):
        return self.p.get(k, default)

    def get_int(self, k, default=None, minval=None, maxval=None):
        v = self.p.get(k)
        return default if v is None else int(v)

    def get_float(self, k, default=None, **kw):
        v = self.p.get(k)
        if v is None:
            if default is None and k in ("X", "Y"):
                raise GErr("fehlt " + k)
            return default
        return float(v)

    def respond_info(self, m):
        self.out.append(m)

    def error(self, m):
        return GErr(m)


class FReactor:
    def __init__(self):
        self.t = 0.0

    def monotonic(self):
        return self.t

    def pause(self, t):
        import time as _t
        _t.sleep(0.05)
        self.t = t


class Obj:
    def __init__(self, st):
        self.st = st

    def get_status(self, ev):
        return self.st


class FGcode:
    def __init__(self, printer):
        self.cmds = {}
        self.scripts = []
        self.printer = printer
        self.seen_home_at = []

    def register_command(self, n, fn, desc=None):
        self.cmds[n] = fn

    def run_script_from_command(self, s):
        self.scripts.append(s)
        if s == "G28 Z":
            m = self.printer.objs["k2_resume"]
            self.seen_home_at.append(m.z_home_at)
            if self.printer.fail_g28:
                raise GErr("No trigger")


class FMesh:
    def calc_z(self, x, y):
        return 0.001 * (x - 175.0) + 0.0005 * (y - 175.0)


class FBedMesh:
    def __init__(self, mesh):
        self.mesh = mesh

    def get_mesh(self):
        return self.mesh


class FPrinter:
    config_error = Exception

    def __init__(self):
        self.reactor = FReactor()
        self.objs = {}
        self.fail_g28 = False
        self.gcode = FGcode(self)
        self.objs["gcode"] = self.gcode
        self.objs["toolhead"] = Obj({"homed_axes": "xyz",
                                     "position": [100, 100, 2.0, 0]})
        self.objs["print_stats"] = Obj({"state": "standby"})
        self.objs["virtual_sdcard"] = type("SD", (), {
            "sdcard_dirname": TMP,
            "get_status": lambda s, e: {"file_path": None,
                                        "file_position": 0}})()
        self.objs["configfile"] = Obj({"settings": {
            "bed_mesh": {"mesh_min": [5, 5], "mesh_max": [345, 345]},
            "z_tilt": {"points": [[5, 175], [345, 175]]}}})
        self.objs["gcode_macro _PI_FREIGABE"] = Obj({"allow_move": True})
        self.objs["k2_box"] = Obj({"chain_error": ""})
        self.objs["bed_mesh"] = FBedMesh(FMesh())

    def get_reactor(self):
        return self.reactor

    def lookup_object(self, n, default=KeyError):
        if n in self.objs:
            return self.objs[n]
        if default is KeyError:
            raise KeyError(n)
        return default


class FConfig:
    def __init__(self, printer):
        self.printer = printer

    def get_printer(self):
        return self.printer

    def getfloat(self, k, default=None, **kw):
        return default


def _modul():
    pr = FPrinter()
    m = R.load_config(FConfig(pr))
    pr.objs["k2_resume"] = m
    return pr, m


def test_modul():
    pr, m = _modul()
