def datei_generator(n=20):
    L = ["; generated by K2-Erstdruck-Generator 1.0 (Test)", "",
         "EXCLUDE_OBJECT_DEFINE NAME=Wuerfel20 CENTER=175.000,175.000 "
         "POLYGON=[[165,165],[185,165],[185,185],[165,185]]",
         "SET_PRINT_STATS_INFO TOTAL_LAYER=%d" % n,
         "START_PRINT EXTRUDER_TEMP=220 BED_TEMP=60", "G90",
         "M83 ; relative Extrusion", "G92 E0", "M107", "M204 S2000",
         "G1 Z5 F600", "G0 X20.000 Y10.000 F12000", "G1 Z0.300 F600",
         "G1 E2.00 F300", "G1 X120.000 Y10.000 E9.978 F1500"]
    for i in range(1, n + 1):
        z = round(0.25 + 0.2 * (i - 1), 3)
        L += [";BEFORE_LAYER_CHANGE", ";%.3f" % z, "G1 E-0.80 F2400",
              "G1 Z%.3f F1800" % (z + 0.2), ";LAYER_CHANGE",
              ";Z:%.3f" % z, ";HEIGHT:0.200",
              "SET_PRINT_STATS_INFO CURRENT_LAYER=%d" % i]
        if i == 3:
            L += ["M106 S255 ; Bauteillüfter an"]
        L += ["EXCLUDE_OBJECT_START NAME=Wuerfel20",
              "G0 X184.379 Y184.379 F12000", "G1 Z%.3f F1800" % z,
              "G1 E0.80 F2400"]
        L += _quadrat(175, 175, 9.6, z)
        L += ["EXCLUDE_OBJECT_END NAME=Wuerfel20"]
    L += ["; Druckende", "END_PRINT", "",
          "; filament used [mm] = 100.0", "; total layers count = %d" % n]
    return "\n".join(L) + "\n"


