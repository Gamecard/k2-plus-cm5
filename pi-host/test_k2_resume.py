def test_echtdateien():
    env = os.environ.get("K2_RESUME_ECHTDATEIEN", "")
    pfade = [p for p in env.split(os.pathsep) if p]
    if not pfade:
        print("SKIP Echtdateien (K2_RESUME_ECHTDATEIEN nicht gesetzt)")
        return
    for i, p in enumerate(pfade):
        s = R.scan_file(p)
        n = s["total"]
        lay = max(2, n // 3)
        out = os.path.join(TMP, "echt%d.gcode" % i)
        plan = R.write_resume(p, out, lay, "keep")
        a = open(p, "rb").read()
        b = open(out, "rb").read()
        mark = ("; ---- Originaldatei ab Schicht %d ----\n" % lay).encode()
        rest = b[b.index(mark) + len(mark):]
        check("Echtdatei %d: %d Schichten, Rest byte-genau" % (i, n),
              n > 0 and a.endswith(rest), plan["layer"])
        try:
            plan = R.build_plan(R.scan_file(p, layer=lay), lay, "probe",
                                tilt="0")
            ok_ = R.point_free(R.scan_file(p, layer=lay)["snap"]["occ"],
                               *plan["probe_xy"])[0]
            check("Echtdatei %d: freier Antastpunkt %s" % (i, plan["probe_xy"]),
                  ok_)
        except R.ResumeError as exc:
            check("Echtdatei %d: probe ehrlich abgelehnt (%s)" % (i, exc), True)


