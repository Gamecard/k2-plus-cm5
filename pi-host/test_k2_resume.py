def _quadrat(cx, cy, h, z, e=0.4):
    return ["G1 X%.2f Y%.2f F30000" % (cx - h, cy - h),
            "G1 X%.2f Y%.2f E%.3f F3000" % (cx + h, cy - h, e),
            "G1 X%.2f Y%.2f E%.3f" % (cx + h, cy + h, e),
            "G1 X%.2f Y%.2f E%.3f" % (cx - h, cy + h, e),
            "G1 X%.2f Y%.2f E%.3f" % (cx - h, cy - h, e)]


def datei_orca(n=40, wechsel_bei=10):
    L = ["; HEADER_BLOCK_START", "; generated by OrcaSlicer 2.5.0 (Test)",
         "; total layer number: %d" % n, "; HEADER_BLOCK_END", ";",
         "; EXECUTABLE_BLOCK_START",
         "EXCLUDE_OBJECT_DEFINE NAME=teil CENTER=175,175 POLYGON=[[165,165],[185,165],[185,185],[165,185]]",
         "M140 S0", "M104 S0", "START_PRINT EXTRUDER_TEMP=220 BED_TEMP=55",
         "T1", "M109 S220", "M204 S2000", "G1 Z3 F600", "M83",
         "G1 X0 Y150 F12000", "G1 Z0.2 F600",
         "G1 X0 Y0 E15 F6000", "G1 X150 Y0 E15 F6000", "G92 E0", "G1 Z1 F600",
         "G90", "M83"]
    for i in range(1, n + 1):
        z = round(0.2 * i, 3)
        if i == wechsel_bei:
            L += ["G17", "G2 Z%.1f I0.86 J0.86 P1 F10000" % (z + 0.4),
                  "G1 X0 Y245 F30000", "M106 S0", "T0", "M104 S225",
                  ";_FORCE_RESUME_FAN_SPEED", "M106 S255"]
        L += ["G1 E-.8 F2400", ";LAYER_CHANGE", ";Z:%s" % R._fmt(z),
              ";HEIGHT:0.2", "G92 E0",
              "SET_VELOCITY_LIMIT ACCEL=%d" % (5000 if i > 1 else 2000),
              "G1 Z%.2f F30000" % (z + 0.4), "G1 X165 Y165", "G1 Z%.2f" % z,
              "G1 E.8 F2400", "EXCLUDE_OBJECT_START NAME=teil"]
        L += _quadrat(175, 175, 10, z)
        L += ["EXCLUDE_OBJECT_END NAME=teil"]
        if i == 3:
            L += ["M106 S255"]
    L += ["END_PRINT", "; CONFIG_BLOCK_START", "; layer_height = 0.2",
          "; CONFIG_BLOCK_END"]
    return "\n".join(L) + "\n"


