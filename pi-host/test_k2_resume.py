    pr = dict(base)
    pr["k2_resume"] = {"z_home_at": [175.0, 280.0]}
    r = _render(cp, "homing_override", {"Z": "0"}, pr)
    check("G28 Z an freiem Punkt (k2_resume)", "G1 X175.0 Y280.0 F12000" in r,
          r)
    pr["k2_resume"] = {"z_home_at": None}
    r = _render(cp, "homing_override", {"Z": "0"}, pr)
