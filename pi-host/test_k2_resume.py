def _cmds(lines):
    return [l for l in lines if l and not l.startswith(";")]


def test_keep():
    s = R.scan_file(ORCA, layer=20)
    plan = R.build_plan(s, 20, "keep")
    check("keep: sichere Höhe = max(gedruckt, Schicht) + 10",
          abs(plan["safe_z"] - 14.0) < 1e-9, plan["safe_z"])
    pre = _cmds(R.build_preamble(plan, "orca.gcode"))
    check("keep: kein G28", not any(l.startswith("G28") for l in pre), pre)
    i_begin = pre.index("KTWO_RESUME_BEGIN MODE=keep LAYER=20 SAFE_Z=14")
    nach = pre[i_begin + 1:]
    erste_fahrt = next(l for l in nach if l.split()[0] in ("G0", "G1") or
                       l.startswith("T"))
    check("keep: erste Fahrt nur Z hoch", erste_fahrt == "G1 Z14 F600",
          erste_fahrt)
    i_t = pre.index("T0")
    i_xy = pre.index("G0 X165 Y165 F12000")
    check("keep: Werkzeug vor X/Y, X/Y erst auf sicherer Höhe",
          i_t < i_xy and pre[i_xy - 1] == "G1 Z14 F600", pre[i_xy - 2:i_xy + 2])
    check("keep: absenken auf erste Z nach X/Y", pre[i_xy + 1] == "G1 Z4.4 F600",
          pre[i_xy + 1])
    check("keep: Vordrucken + Zustand", "_PI_WIEDEREINSTIEG_VORDRUCK E=25" in pre and
          "M106 S255" in pre and "M83" in pre and
          "M104 S225" in pre and "M109 S225" in pre, pre)


def test_probe():
    s = R.scan_file(ORCA, layer=20)
    try:
        R.build_plan(s, 20, "probe", tilt="auto")
        check("probe/auto: hohes Teil -> kein Ausrichten -> Abbruch", False)
    except R.ResumeError as exc:
        check("probe/auto: hohes Teil -> kein Ausrichten -> Abbruch",
              "TILT=0" in str(exc), str(exc))
    plan = R.build_plan(s, 20, "probe", tilt="0")
    px, py = plan["probe_xy"]
    occ = s["snap"]["occ"]
    check("probe: Antastpunkt frei", R.point_free(occ, px, py)[0], plan)
    check("probe: X = Mitte des Objekts", px == 175.0, plan["probe_xy"])
    check("probe: Warnung ohne Z_TILT", any("Schräglage" in w for w in
                                           plan["warnings"]), plan["warnings"])
    pre = _cmds(R.build_preamble(plan, "orca.gcode"))
    check("probe: G28 X Y, kein G28 Z/G28 allein",
          "G28 X Y" in pre and "G28" not in pre and "G28 Z" not in pre, pre)
    i_h = pre.index("KTWO_RESUME_ZHOME X=%s Y=%s" % (R._fmt(px), R._fmt(py)))
    check("probe: nach Antasten sofort auf sichere Höhe",
          pre[i_h + 1] == "G1 Z%s F600" % R._fmt(plan["safe_z"]), pre[i_h + 1])
    i_f = pre.index("KTWO_RESUME_ZFIX X=%s Y=%s" % (R._fmt(px), R._fmt(py)))
    check("probe: Netz laden vor ZFIX, Offset 0 vorher",
          pre.index("BED_MESH_PROFILE LOAD=default") < i_f and
          pre.index("SET_GCODE_OFFSET Z=0") < i_f)
    check("probe: kein Z_TILT bei TILT=0",
          not any(l.startswith("Z_TILT") for l in pre))
    # niedriges Teil: Ausrichten möglich
    s2 = R.scan_file(ORCA, layer=2)
    plan2 = R.build_plan(s2, 2, "probe", tilt="auto")
    pre2 = _cmds(R.build_preamble(plan2, "orca.gcode"))
    check("probe: niedriges Teil -> Z_TILT_ADJUST auf Z5",
          plan2["tilt"] and "Z_TILT_ADJUST HORIZONTAL_MOVE_Z=5" in pre2,
          (plan2.get("tilt_reason"), pre2))
    try:
        R.build_plan(s, 20, "probe", tilt="1")
        check("probe: TILT=1 erzwingt Prüfung", False)
    except R.ResumeError:
        check("probe: TILT=1 erzwingt Prüfung", True)


