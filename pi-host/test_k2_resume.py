    r = _render(cp, "gcode_macro _PI_WIEDEREINSTIEG_VORDRUCK", {}, {})
    check("PRIME ohne Schacht-Freigabe: keine Extrusion",
          not any(l.startswith("G1") for l in r), r)
    r = _render(cp, "gcode_macro _PI_WIEDEREINSTIEG_BOX_START", {},
                {"k2_box": {"change_enabled": True}})
    check("BOX_START wie START_PRINT", r == ["KTWO_BOX_PRINT_START"], r)
