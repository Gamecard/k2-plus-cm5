class ConfigError(Exception):
    pass


class GcmdError(Exception):
    pass


_SENTINEL = object()


class FakeConfig:
    error = ConfigError

    def __init__(self, printer, werte=None, name="k2_dateipruefung"):
        self.printer = printer
        self.werte = dict(werte or {})
        self.name = name

    def get_printer(self):
        return self.printer

    def get_name(self):
        return self.name

    def get(self, opt, default=_SENTINEL):
        if opt in self.werte:
            return self.werte[opt]
        if default is _SENTINEL:
            raise ConfigError("fehlt " + opt)
        return default

    def getboolean(self, opt, default=_SENTINEL):
        v = self.get(opt, default)
        return v if isinstance(v, bool) else str(v).lower() in ("1", "true")

    def getlist(self, opt, default=_SENTINEL):
        if opt not in self.werte:
            return default
        v = self.werte[opt]
        return [p.strip() for p in v.split(",")] if v.strip() else []


class FakeGcmd:
    """Wie klippy/gcode.GCodeCommand.get: fehlt der Parameter ohne Default
    -> Fehler."""

    def __init__(self, **p):
        self.p = p
        self.out = []

    def get(self, k, default=_SENTINEL):
        if k not in self.p:
            if default is _SENTINEL:
                raise GcmdError("missing " + k)
            return default
        return self.p[k]

    def respond_info(self, msg):
        self.out.append(msg)

    def error(self, msg):
        return GcmdError(msg)


class FakeSD:
    """virtual_sdcard: sdcard_dirname + get_file_list wie Upstream 9cb9975."""

    def __init__(self, verz):
        self.sdcard_dirname = verz
        self.listen = 0

    def get_file_list(self, check_subdirs=False):
        self.listen += 1
        flist = []
        for root, dirs, files in os.walk(self.sdcard_dirname,
                                         followlinks=True):
            for name in files:
                ext = name[name.rfind('.') + 1:]
                if ext not in m.VALID_GCODE_EXTS:
                    continue
                full = os.path.join(root, name)
                flist.append((full[len(self.sdcard_dirname) + 1:],
                              os.path.getsize(full)))
        return sorted(flist, key=lambda f: f[0].lower())


class FakeGcode:
    def __init__(self):
        self.cmds = {}
        self.raw = []

    def register_command(self, name, fn, desc=None):
        self.cmds[name] = fn

    def respond_raw(self, z):
        self.raw.append(z)


class FakeReactor:
    NOW = 0.
    NEVER = 9e99

    def monotonic(self):
        return 1000.

    def register_timer(self, cb, when):
        return cb


class SyncExecutor:
    def __init__(self):
        self.aufrufe = []

    def submit(self, fn, *args, **kw):
        self.aufrufe.append(getattr(fn, "__name__", "?"))
        return fn(*args, **kw)

    def wrap_obj(self, obj):
        return obj


class FakeAio:
    def __init__(self):
        self.executors = []

    def allocate_executor(self, name=""):
        ex = SyncExecutor()
        ex.name = name
        self.executors.append(ex)
        return ex


class FakePrinter:
    def __init__(self, verz, aio=None):
        self.gcode = FakeGcode()
        self.reactor = FakeReactor()
        self.objs = {"gcode": self.gcode}
        if verz is not None:
            self.objs["virtual_sdcard"] = FakeSD(verz)
        self.aio = aio

    def get_reactor(self):
        return self.reactor

    def get_state_message(self):
        return ("Printer is ready", "ready")

    def register_event_handler(self, ev, cb):
        pass

    def lookup_object(self, name, default=None):
        return self.objs.get(name, default)

    def load_object(self, config, name, default=_SENTINEL):
        if name == "aio_executor" and self.aio is not None:
            return self.aio
        if default is _SENTINEL:
            raise ConfigError("Unable to load module '%s'" % name)
        return default


def baue(verz, aio=None, **werte):
    pr = FakePrinter(verz, aio)
    mod = m.load_config(FakeConfig(pr, werte))
    return pr, mod


def pruefe(pr, mod, name, **extra):
    """KTWO_DATEI_PRUEFEN FILENAME=name -> (ok, fehlertext, neue Konsolen-
    zeilen)."""
    vorher = len(pr.gcode.raw)
    g = FakeGcmd(FILENAME=name, **extra) if name is not None else FakeGcmd()
    try:
        pr.gcode.cmds["KTWO_DATEI_PRUEFEN"](g)
        return True, "", pr.gcode.raw[vorher:]
    except GcmdError as e:
        return False, str(e), pr.gcode.raw[vorher:]


