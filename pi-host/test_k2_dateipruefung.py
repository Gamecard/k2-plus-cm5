def test_regeln(verz):
    schreibe(verz, "x1c_orca.gcode", orca_bambu())
    schreibe(verz, "bambu_ohne_modell.gcode", bambu_ohne_modell())
    schreibe(verz, "orca_k2.gcode", orca_k2())
    schreibe(verz, "creality_print.gcode", creality_print())
    schreibe(verz, "eigene.gcode", eigene())
    schreibe(verz, "unbekannt.gcode", unbekannt())
    schreibe(verz, "kommentare.gcode", nur_kommentare())
    pr, mod = baue(verz)

    gut, txt, _ = pruefe(pr, mod, "x1c_orca.gcode")
    check("a) Orca mit Bambu-Profil (printer_model) abgelehnt", not gut)
    check("a) Meldung wie gefordert",
          txt == "[k2_dateipruefung] Datei ist für ‚Bambu Lab X1 Carbon‘ "
                 "gesliced, nicht für den K2 Plus – im Slicer Drucker "
                 "‚Creality K2 Plus 0.4 nozzle - Pi‘ wählen und neu slicen "
                 "(MakerWorld-3MF mit Strg+I importieren statt öffnen). "
                 "Druck nicht gestartet.", txt)
    check("a) Status abgelehnt + Modell",
          mod.get_status()["letzte"]["ergebnis"] == "abgelehnt"
          and mod.get_status()["letzte"]["modell"] == "Bambu Lab X1 Carbon")

    gut, txt, _ = pruefe(pr, mod, "bambu_ohne_modell.gcode")
    check("b) Bambu-Befehle ohne printer_model abgelehnt", not gut)
    befehle = re.search(r"Bambu-Lab-Befehle \(([^)]*)\)", txt)
    liste = befehle.group(1).split(", ") if befehle else []
    check("b) Meldung nennt die Befehle in Reihenfolge",
          liste[:4] == ["M1006", "M1007", "M620", "M621"]
          and all(c in liste for c in ("G380", "M1002", "M975", "G29.1",
                                       "M960", "M142", "M977")), txt)
    check("b) Meldung: kein printer_model, Profil + Strg+I, Großschreibung",
          "kein Druckerprofil (printer_model)" in txt
          and "Im Slicer Drucker ‚Creality K2 Plus 0.4 nozzle - Pi‘" in txt
          and "Strg+I" in txt and "Druck nicht gestartet." in txt, txt)

    gelesen = {}
    for name, modell in (("orca_k2.gcode", "Creality K2 Plus"),
                         ("creality_print.gcode", "Creality K2 Plus"),
                         ("eigene.gcode", "K2 Plus")):
        gut, txt, kons = pruefe(pr, mod, name)
        check("c) %s läuft durch (%s)" % (name, modell),
              gut and mod.letzte["ergebnis"] == "ok"
              and mod.letzte["modell"] == modell, txt)
        check("c) %s: OK-Hinweis in der Konsole" % name,
              kons == ["// [k2_dateipruefung] ‚%s‘ geprüft: Druckerprofil "
                       "‚%s‘ – ok" % (name, modell)], kons)
        gelesen[name] = mod.letzte["gelesen"]
    check("c) Orca-K2 (< 512 KiB): Datei genau einmal gelesen, Modell im Ende",
          gelesen["orca_k2.gcode"] == os.path.getsize(
              os.path.join(verz, "orca_k2.gcode")), gelesen)

    gut, txt, kons = pruefe(pr, mod, "unbekannt.gcode")
    check("c) ohne Modell und ohne Bambu-Befehl: läuft",
          gut and mod.letzte["ergebnis"] == "unbekannt")
    check("c) … nur Hinweis „Druckerprofil unbekannt“ (// , k2_konsole)",
          len(kons) == 1 and kons[0].startswith("// [k2_dateipruefung] ")
          and "Druckerprofil unbekannt" in kons[0]
          and "trotzdem gedruckt" in kons[0], kons)

    gut, txt, kons = pruefe(pr, mod, "kommentare.gcode")
    check("Bambu-Befehle nur in Kommentaren/M117-Text: nicht gewertet",
          gut and mod.letzte["ergebnis"] == "unbekannt"
          and mod.letzte["bambu"] == [], (txt, mod.letzte))


