def _baue_upstream(up, verz, mit_modul=True):
    ucfg, ugcode, umacro, usd = up

    class UPrinter:
        command_error = ugcode.CommandError
        config_error = ucfg.error

        def __init__(self):
            self.reactor = UReactor()
            self.objects = {}
            self.handlers = {}
            self.aio = FakeAio()

        def get_reactor(self):
            return self.reactor

        def get_start_args(self):
            return {}

        def get_state_message(self):
            return ("Printer is ready", "ready")

        def lookup_object(self, name, default=configparser.Error):
            if name in self.objects:
                return self.objects[name]
            if default is configparser.Error:
                raise self.config_error("Unknown config object '%s'" % name)
            return default

        def lookup_objects(self, module=None):
            return list(self.objects.items())

        def load_object(self, config, section, default=configparser.Error):
            if section in self.objects:
                return self.objects[section]
            if section == "aio_executor":
                return self.aio
            if default is configparser.Error:
                raise self.config_error("Unable to load module '%s'"
                                        % section)
            return default

        def register_event_handler(self, ev, cb):
            self.handlers.setdefault(ev, []).append(cb)

        def send_event(self, ev, *args):
            return [cb(*args) for cb in self.handlers.get(ev, [])]

        def invoke_shutdown(self, msg):
            raise AssertionError("Shutdown: %s" % msg)

        def request_exit(self, r):
            pass

    pr = UPrinter()
    gc = ugcode.GCodeDispatch(pr)
    pr.objects["gcode"] = gc
    out = []
    gc.register_output_handler(out.append)
    pr.objects["print_stats"] = UPrintStats()
    fc = configparser.RawConfigParser()
    fc.read_string("[gcode_macro]\n[virtual_sdcard]\npath: %s\n" % verz)
    pr.objects["gcode_macro"] = umacro.PrinterGCodeMacro(
        ucfg.ConfigWrapper(pr, fc, {}, "gcode_macro"))
    sd = usd.VirtualSD(ucfg.ConfigWrapper(pr, fc, {}, "virtual_sdcard"))
    pr.objects["virtual_sdcard"] = sd
    pr.objects["gcode_macro SDCARD_PRINT_FILE"] = umacro.GCodeMacro(
        _sektion(ucfg, pr, MAKRO_CFG, "gcode_macro SDCARD_PRINT_FILE"))
    if mit_modul:
        pr.objects["k2_dateipruefung"] = m.load_config(
            _sektion(ucfg, pr, MODUL_CFG, "k2_dateipruefung"))
    pr.send_event("klippy:connect")
    gc._handle_ready()
    return pr, gc, sd, out


def _start(up, pr, gc, sd, out, zeile):
    """Zeile wie von Moonraker senden. -> (gestartet, fehler, ausgabe)."""
    sd.work_timer = None
    pr.reactor.timers[:] = []
    sd._reset_file()
    del out[:]
    try:
        gc.run_script_from_command(zeile)
        err = ""
    except up[1].CommandError as e:
        err = str(e)
    return (sd.current_file is not None and bool(pr.reactor.timers)), err, \
        list(out)


