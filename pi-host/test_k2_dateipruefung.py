def test_abschalten(verz):
    schreibe(verz, "x1c.gcode", orca_bambu())
    pr, mod = baue(verz, aktiv=False)
    gut, txt, kons = pruefe(pr, mod, "x1c.gcode")
    check("aktiv: False lässt alles durch (mit Warnung)",
          gut and mod.letzte["ergebnis"] == "aus" and len(kons) == 1
          and kons[0].startswith("// [k2_dateipruefung] Prüfung abgeschaltet"),
          kons)
    gut, txt, _ = pruefe(pr, mod, "gibt-es-nicht.gcode")
    check("abgeschaltet: auch fehlende Datei nicht geprüft (BASE meldet)", gut)

    pr, mod = baue(verz)
    cmd = pr.gcode.cmds["KTWO_DATEI_PRUEFUNG"]
    vorher = len(pr.gcode.raw)
    cmd(FakeGcmd(AKTIV="0"))
    kons = pr.gcode.raw[vorher:]
    check("AKTIV=0: Konsolenwarnung „bis zum Neustart“",
          not mod.aktiv and len(kons) == 1 and "AUSGESCHALTET bis zum "
          "Neustart" in kons[0] and kons[0].startswith("// "), kons)
    gut, _t, _k = pruefe(pr, mod, "x1c.gcode")
    check("AKTIV=0: Bambu-Datei läuft durch", gut)
    cmd(FakeGcmd(AKTIV="1"))
    check("AKTIV=1: Konsolenmeldung", "wieder EINGESCHALTET" in
          pr.gcode.raw[-1])
    gut, _t, _k = pruefe(pr, mod, "x1c.gcode")
    check("AKTIV=1: Bambu-Datei wieder abgelehnt", not gut)
    g = FakeGcmd()
    cmd(g)
    check("KTWO_DATEI_PRUEFUNG ohne AKTIV: Zustand + letzte Prüfung",
          g.out and "Prüfung AKTIV" in g.out[0] and "erlaubte Modelle: K2"
          in g.out[0] and "‚x1c.gcode‘ -> abgelehnt" in g.out[0], g.out)
    try:
        cmd(FakeGcmd(AKTIV="2"))
        r = False
    except GcmdError as e:
        r = "AKTIV=0|1" in str(e)
    check("AKTIV=2 abgelehnt", r)
    st = mod.get_status()
    check("get_status: aktiv, erlaubte_modelle, letzte",
          st["aktiv"] is True and st["erlaubte_modelle"] == ["K2"]
          and st["letzte"]["datei"] == "x1c.gcode")


