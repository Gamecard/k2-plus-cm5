def _vorschau(kb):
    """Vorschaubild-Kommentare (wie Orca/Creality Print) mit ~kb KiB."""
    zeile = "; " + "iVBORw0KGgoAAAANSUhEUgAAASwAAAEsCAYAAAB5fY51AAAgAElEQVR4"[:76]
    n = max(1, kb * 1024 // (len(zeile) + 1))
    return ("; THUMBNAIL_BLOCK_START\n; thumbnail begin 300x300 %d\n%s\n"
            "; thumbnail end\n; THUMBNAIL_BLOCK_END\n"
            % (n * 77, "\n".join([zeile] * n)))


def _bahnen(n, start=0):
    out = []
    for i in range(start, start + n):
        out.append("G1 X%.3f Y%.3f E%.5f" % (10 + i % 300 * 0.5,
                                              20 + i % 211 * 0.7,
                                              0.0123 + i % 7 * 0.001))
    return "\n".join(out) + "\n"


def _config_block(modell, extra=""):
    zeilen = ["; CONFIG_BLOCK_START", "; bed_temperature = 60",
              "; filament_type = PLA"]
    zeilen += ["; option_%03d = %d" % (i, i) for i in range(300)]
    if extra:
        zeilen.append(extra)
    if modell is not None:
        zeilen.append("; printer_model = %s" % modell)
    zeilen += ["; printer_settings_id = Profil", "; z_hop = 0.4",
               "; CONFIG_BLOCK_END"]
    return "\n".join(zeilen) + "\n"


